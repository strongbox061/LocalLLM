#!/usr/bin/env python3
"""Builds the word matchers of Pi's extensions and the Open WebUI tool from lang/phrases.json.

    python3 lang/build.py           write pi/extensions/lang-words.ts and the generated block of the tool
    python3 lang/build.py --check   fail if either is out of date (nothing is written)

Phrase syntax (lang/phrases.json):
    word*       the word with any ending ("fehler*": Fehler, Fehlermeldung)
    a … b       a, then b later in the same sentence (also "a…b")
    {engine}    a search engine name (only in named_engine)
    ^phrase     at the start of the message (after an optional "please")
    phrase$     at the end of the message (before an optional "please" and punctuation)
    ~phrase     anywhere, in a rule that otherwise matches at the start
A space matches spaces or a hyphen, a hyphen matches a hyphen, a space or nothing, an apostrophe is optional.
Text and phrases are compared lower-cased with accents removed (see norm()). Phrases in scripts written without
spaces (Chinese, Japanese, Thai) match anywhere, even in a "starts with" rule; all others match whole words only.
"""

import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PHRASES = ROOT / "lang" / "phrases.json"
TS_OUT = ROOT / "pi" / "extensions" / "lang-words.ts"
TOOL = ROOT / "services" / "search_gateway_engine.py"
BEGIN = "# --- lang-words: generated by lang/build.py from lang/phrases.json, don't edit by hand ---"
END = "# --- end of lang-words ---"

# Accents removed by norm(): Latin/Greek/Cyrillic diacritics, Hebrew points, Arabic vowel marks and hamza.
# Marks that are part of a letter in Indic scripts, Thai, Japanese or Korean are kept.
MARKS = "̀-֑ͯ-ׇֽֿׁׂًׅׄ-ٰٟ"
# Same-meaning characters written differently: curly apostrophes, Greek final sigma, Arabic/Persian yeh and kaf,
# and the Persian zero-width non-joiner (written or left out at will).
SAME = {"’": "'", "‘": "'", "ʼ": "'", "`": "'", "ς": "σ",
        "ي": "ی", "ى": "ی", "ك": "ک", "‌": "", "‍": ""}
NOSPACE = re.compile(r"[฀-๿぀-ヿ㐀-鿿豈-﫿]")
GAP_MARK = "…"
PUNCT = ".!?,:;"
# Characters that end a sentence, as the inside of a regex character class.
STOP = r".?!。？！\n"

_MARKS_RE = re.compile(f"[{MARKS}]")


def norm(text: str) -> str:
    t = unicodedata.normalize("NFD", str(text).lower())
    t = unicodedata.normalize("NFC", _MARKS_RE.sub("", t))
    return "".join(SAME.get(c, c) for c in t)


class Flavor:
    """The regex dialect: JavaScript (u flag) or Python re."""

    def __init__(self, js: bool):
        self.js = js
        # A vowel sign is a mark, not a letter, but part of the word: "बग" (bug) isn't in "बगीचा" (garden). Python's re
        # has no \p{M}; the marks norm() keeps in scripts written with spaces are in the Indic blocks.
        word = r"[\p{L}\p{M}\p{N}]" if js else r"[\w\u0300-\u036f\u0900-\u0dff]"
        self.before = f"(?<!{word})"
        self.after = f"(?!{word})"
        self.letters = r"[\p{L}\p{M}\p{N}_]*" if js else word + "*"
        stop = STOP
        self.gap_spaced = rf"(?:[\s-]+[^{stop}]{{0,80}}?)?[\s-]+"
        self.gap_tight = rf"[^{stop}]{{0,80}}?"
        self.end_punct = r"[\s.!?。！？،؟]*$"


def escape(text: str) -> str:
    return re.sub(r"([\\^$.|?*+()\[\]{}/])", r"\\\1", text)


def piece(text: str, f: Flavor, tight: bool, engine: str) -> str:
    """One phrase without anchors or gaps, as a regex."""
    out = []
    i = 0
    while i < len(text):
        c = text[i]
        if text.startswith("{engine}", i):
            if not engine:
                raise ValueError(f"{{engine}} outside named_engine: {text!r}")
            out.append(rf"\s*{engine}\s*")
            i += len("{engine}")
            continue
        if c == "*":
            out.append(f.letters)
        elif c == " ":
            out.append(r"\s*" if tight else r"[\s-]+")
        elif c == "-":
            out.append(r"[\s-]*")
        elif c == "'":
            out.append("'?")
        elif c in PUNCT:
            out.append(r"\s*" + escape(c))
        else:
            out.append(escape(c))
        i += 1
    return "".join(out)


def phrase_re(raw: str, f: Flavor, default_anchor: str, engine: str = "") -> tuple:
    """A phrase from phrases.json as (anchor, regex, word boundary before, word boundary after)."""
    anchor = default_anchor
    p = norm(raw).strip()
    if p.startswith("^"):
        anchor, p = "start", p[1:]
    elif p.startswith("~"):
        anchor, p = "any", p[1:]
    if p.endswith("$"):
        anchor, p = "end", p[:-1]
    p = p.strip()
    if not p:
        raise ValueError(f"empty phrase: {raw!r}")
    tight = bool(NOSPACE.search(p))
    if tight and anchor == "start" and not raw.lstrip().startswith("^"):
        anchor = "any"  # no spaces, and the verb or question word often comes late: anywhere
    if tight and len(re.sub(r"[\s*…]|\{engine\}", "", p)) < 2:
        raise ValueError(f"phrase in a script without spaces needs at least 2 characters: {raw!r}")
    parts = [s.strip() for s in p.split(GAP_MARK)]
    gap = f.gap_tight if tight else f.gap_spaced
    body = gap.join(piece(s, f, tight, engine) for s in parts)
    before = not tight and not parts[0].startswith("{engine}")
    after = not tight and not (parts[-1].endswith("{engine}") or parts[-1][-1] in PUNCT)
    return anchor, body, before, after


def alternation(patterns) -> str:
    seen, out = set(), []
    for p in sorted(patterns, key=lambda s: (-len(s), s)):
        if p not in seen:
            seen.add(p)
            out.append(p)
    return "|".join(out)


def combine(phrases, f: Flavor, please: str) -> str:
    """One regex for many phrases: grouped by anchor and word boundaries, so each is written once."""
    groups = {}
    for anchor, body, before, after in phrases:
        groups.setdefault((anchor, before, after), []).append(body)
    out = []
    for (anchor, before, after), bodies in sorted(groups.items()):
        g = f"(?:{alternation(bodies)})" if len(bodies) > 1 else bodies[0]
        g = (f.before if before else "") + g + (f.after if after else "")
        if anchor == "start":
            g = rf"^\s*(?:(?:{please})[\s,]+)?{g}"
        elif anchor == "end":
            g = rf"{g}(?:[\s,]+(?:{please}))?{f.end_punct}"
        out.append(g)
    return "|".join(out)


PLEASE_TOKEN, ENGINE_TOKEN = "<<please>>", "<<engine>>"


def please_re(data: dict, f: Flavor) -> str:
    return alternation(piece(norm(p), f, bool(NOSPACE.search(norm(p))), "")
                       for lang in data["languages"].values() for p in lang.get("please", []))


def engine_re(data: dict, f: Flavor) -> str:
    names = "|".join(escape(e) for e in data["engines"])
    tail = r"(?:[-']?[\p{L}\p{M}]+)?" if f.js else r"(?:[-']?\w+)?"
    return f"({names}){tail}"


def build_rule(data: dict, rule: str, f: Flavor) -> str:
    info = data["rules"][rule]
    langs = data["languages"]
    anchor = info.get("anchor", "any")
    please = PLEASE_TOKEN if f.js else please_re(data, f)
    engine = (ENGINE_TOKEN if f.js else engine_re(data, f)) if rule == "named_engine" else ""
    phrases, extra = [], []
    for code, lang in langs.items():
        entry = lang.get(rule)
        if not entry:
            continue
        try:
            if rule == "named_source":
                phrases += [phrase_re(p, f, anchor) for p in entry.get("phrases", [])]
                verbs = combine([phrase_re(v, f, "any") for v in entry["verbs"]], f, please)
                nouns = combine([phrase_re(n, f, "any") for n in entry["nouns"]], f, please)
                tight = any(NOSPACE.search(norm(x)) for x in entry["verbs"] + entry["nouns"])
                gap = f.gap_tight if tight else rf"[^{STOP}]{{0,120}}?"
                a, b = (nouns, verbs) if lang.get("verb_last") else (verbs, nouns)
                extra.append(f"(?:{a}){gap}(?:{b})")
            else:
                phrases += [phrase_re(p, f, anchor, engine) for p in entry]
        except (ValueError, re.error) as e:
            raise SystemExit(f"lang/phrases.json: {code}.{rule}: {e}")
    return "|".join(x for x in [combine(phrases, f, please), *extra] if x)


def months_re(data: dict) -> str:
    """Month names for the tool's year filter, which runs on the raw query: written forms and accent-free ones."""
    out = []
    for lang in data["languages"].values():
        for m in lang.get("months", []):
            for form in {m.lower(), norm(m)}:
                out.append(re.sub(r"\\\*", r"\\w*", re.sub(r"\\ ", r"\\s+", re.escape(form))))
    return alternation(out)


def js_regex(pattern: str, flags: str = "u") -> str:
    return "/" + pattern.replace("/", r"\/") + "/" + flags


def build_ts(data: dict) -> str:
    js = Flavor(True)
    rules = [(r, i) for r, i in data["rules"].items() if "pi" in i["for"] and r != "please"]
    out = [
        "// lang-words.ts: generated by lang/build.py from lang/phrases.json. Don't edit by hand: change",
        "// lang/phrases.json, then run `python3 lang/build.py`.",
        "// Location: ~/.pi/agent/extensions/lang-words.ts",
        "//",
        f"// The word rules of Pi's extensions in {len(data['languages'])} languages. Test a message with "
        "has(RULE, text): the text is",
        "// lower-cased and its accents removed (norm), as the phrases were.",
        "",
        f"const MARKS = /[{MARKS}]/gu;",
        "const SAME: Record<string, string> = " + json.dumps(SAME, ensure_ascii=True) + ";",
        "export function norm(text: string): string {",
        '  const t = String(text ?? "").toLowerCase().normalize("NFD").replace(MARKS, "").normalize("NFC");',
        '  return t.replace(/[\\u2019\\u2018\\u02bc`\\u03c2\\u064a\\u0649\\u0643\\u200c\\u200d]/g, (c) => SAME[c] ?? c);',
        "}",
        "",
        "// Words allowed before a phrase that starts the message (please, por favor...), and the search engine names.",
        f"const PLEASE = String.raw`{please_re(data, js)}`;",
        f"const ENGINE = String.raw`{engine_re(data, js)}`;",
        "",
    ]
    for rule, info in rules:
        pattern = build_rule(data, rule, js)
        if rule == "question_start":
            pattern = r"[?？؟]\s*$|^\s*¿|" + pattern
        flags = "gu" if rule == "local_current" else "u"
        out.append(f"// {info['about']}")
        if PLEASE_TOKEN in pattern or ENGINE_TOKEN in pattern:
            assert "`" not in pattern and "${" not in pattern, rule
            out.append(f"export const {rule.upper()} = new RegExp(String.raw`{pattern}`"
                       f'.replaceAll("{PLEASE_TOKEN}", PLEASE).replaceAll("{ENGINE_TOKEN}", ENGINE), "{flags}");')
        else:
            out.append(f"export const {rule.upper()} = {js_regex(pattern, flags)};")
        out.append("")
    engines = json.dumps(data["engines"])
    out += [
        "/** Does the text contain one of the rule's phrases? */",
        "export function has(rule: RegExp, text: string): boolean {",
        "  rule.lastIndex = 0;",
        "  return rule.test(norm(text));",
        "}",
        "",
        "/** The search engine named in \"search on <engine>\" (lower case), if any. */",
        "export function namedEngine(text: string): string | undefined {",
        "  const m = norm(text).match(NAMED_ENGINE);",
        "  return m?.slice(1).find((x) => x !== undefined);",
        "}",
        "",
        f"export const ENGINES = {engines};",
        "",
        "// Pi loads every .ts file in extensions/ as an extension; this one only provides the words.",
        "export default function () {}",
        "",
    ]
    return "\n".join(out)


def build_py_block(data: dict) -> str:
    py = Flavor(False)
    rules = [(r, i) for r, i in data["rules"].items() if "tool" in i["for"] and r not in ("months", "please")]
    out = [
        BEGIN,
        "# The word rules in " + str(len(data["languages"])) + " languages. Search lang_norm(text) with these, except MONTHS (raw text).",
        f'_LANG_MARKS = re.compile("[{MARKS.encode("unicode_escape").decode()}]")',
        "_LANG_SAME = str.maketrans(" + json.dumps(SAME, ensure_ascii=True) + ")",
        "",
        "",
        "def lang_norm(text):",
        '    """Lower case, accents removed: how the phrases below are written."""',
        '    t = unicodedata.normalize("NFD", str(text or "").lower())',
        '    return unicodedata.normalize("NFC", _LANG_MARKS.sub("", t)).translate(_LANG_SAME)',
        "",
        "",
        f'MONTHS = r"{months_re(data)}"',
    ]
    for rule, info in rules:
        pattern = build_rule(data, rule, py)
        re.compile(pattern)
        assert '"' not in pattern, f"{rule}: a double quote can't go in the generated Python"
        out.append(f"# {info['about']}")
        out.append(f"LANG_{rule.upper()}_RE = re.compile(r\"{pattern}\")")
    out.append(END)
    return "\n".join(out)


def tool_with_block(tool_text: str, block: str) -> str:
    start, end = tool_text.find(BEGIN), tool_text.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"{TOOL.relative_to(ROOT)}: the lang-words markers are missing")
    return tool_text[:start] + block + tool_text[end + len(END):]


def main() -> int:
    check = "--check" in sys.argv[1:]
    data = json.loads(PHRASES.read_text(encoding="utf-8"))
    ts = build_ts(data)
    tool_old = TOOL.read_text(encoding="utf-8")
    tool_new = tool_with_block(tool_old, build_py_block(data))
    stale = []
    if not TS_OUT.exists() or TS_OUT.read_text(encoding="utf-8") != ts:
        stale.append(TS_OUT)
    if tool_new != tool_old:
        stale.append(TOOL)
    if check:
        for p in stale:
            print(f"Out of date: {p.relative_to(ROOT)} (run python3 lang/build.py)")
        if not stale:
            print("lang-words: up to date")
        return 1 if stale else 0
    TS_OUT.write_text(ts, encoding="utf-8")
    TOOL.write_text(tool_new, encoding="utf-8")
    for p in stale:
        print(f"Written: {p.relative_to(ROOT)}")
    if not stale:
        print("lang-words: up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
