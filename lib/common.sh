# pin_image <repo@sha256:digest> <compose file>: when the image tag the compose file uses for that repository isn't
# here yet, pull exactly that digest and give it the tag, so `compose up` uses the recorded version.
pin_image() {
    local ref="$1" compose="$2" repo tag
    [[ "$ref" == *@sha256:* && -f "$compose" ]] || return 0
    repo="${ref%@*}"
    tag="$(grep -oE "image: *(docker\.io/)?${repo//./\\.}:[^ \"]+" "$compose" | head -1 | sed -E 's/^image: *(docker\.io\/)?//')"
    tag="${tag//\$\{SEARXNG_VERSION:-latest\}/latest}"
    [[ -n "$tag" ]] || return 0
    docker_cmd image inspect "$tag" >/dev/null 2>&1 && return 0
    echo "Using the recorded version of $repo: ${ref#*@}"
    docker_cmd pull "$ref"
    docker_cmd tag "$ref" "$tag"
}

# Only you may read Open WebUI's signing key (whoever has it can log in as any user), its database (your chats) and
# the backup folder (copies of both, and of the other settings). Run by backup.sh, restore.sh and
# services/open-webui.sh; tests/restorability-check.sh checks it.
make_private() {
    local f
    for f in "$BACKUP_DIR" "$WEBUI_DATA_DIR"; do
        if [[ -d "$f" ]]; then chmod 700 "$f"; fi
    done
    for f in "$WEBUI_KEY_FILE" "$WEBUI_DATA_DIR"/webui.db "$WEBUI_DATA_DIR"/webui.db-wal "$WEBUI_DATA_DIR"/webui.db-shm; do
        if [[ -f "$f" ]]; then chmod 600 "$f"; fi
    done
}
