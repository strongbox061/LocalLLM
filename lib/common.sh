# install_user_unit <file name> <unit text>: writes ~/.config/systemd/user/<file name> when it differs. Not enabled.
install_user_unit() {
    local unit="$HOME/.config/systemd/user/$1"
    if [[ -f "$unit" ]] && [[ "$2" == "$(cat "$unit")" ]]; then
        echo "$1 is already installed."
    else
        mkdir -p "$(dirname -- "$unit")"
        printf '%s\n' "$2" > "$unit"
        systemctl --user daemon-reload
        echo "Installed $unit"
    fi
}

# wait_for <url> <seconds>
wait_for() {
    local i
    for ((i = 0; i < $2; i++)); do
        curl -fsS -m 2 -o /dev/null "$1" 2>/dev/null && return 0
        sleep 1
    done
    return 1
}

