# webui_settings_single: Open WebUI's settings for single mode, with Open WebUI running on this PC: its tools and
# functions, multilingual-e5-small with the Knowledge bases indexed again (install/open-webui-config.sh), then the chat
# model here without a key, Whisper inside Open WebUI, no Docling, small model or ComfyUI (topology.py). Returns 1 when
# a part failed (each says so).
webui_settings_single() {
    local t rc=0
    "$REPO_DIR/install/open-webui-config.sh" || { warn "install/open-webui-config.sh failed."; rc=1; }
    t="$(mktemp)"
    printf '{"llama_url":"%s","llama_key":"","whisper_model":"small","whisper_url":"","reranking_model":"","docling_url":"","small_model":null,"comfyui":null}\n' "$LLAMA_URL" > "$t"
    "$WEBUI_PYTHON" "$REPO_DIR/open-webui/topology.py" single "$WEBUI_URL" "$WEBUI_DATA_DIR/webui.db" "$WEBUI_KEY_FILE" "$t" \
        || { warn "Some of Open WebUI's settings weren't set back."; rc=1; }
    rm -f "$t"
    return $rc
}

