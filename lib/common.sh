# Puts the DNS override next to docker-compose.yml. Returns 0 when it was added or changed (containers must be
# recreated to use it), 1 when it was already up to date.
searxng_sync_override() {
    local dst="$SEARXNG_DIR/docker-compose.override.yml"
    cmp -s "$SEARXNG_OVERRIDE" "$dst" && return 1
    cp "$SEARXNG_OVERRIDE" "$dst"
    echo "Installed the DNS override: $dst"
    return 0
}

