# install_system_file <path> <content>: writes the file with sudo when it differs. Returns 0 when it was written,
# 1 when it was already up to date.
install_system_file() {
    if [[ -f "$1" ]] && [[ "$2" == "$(cat "$1")" ]]; then
        echo "$1 is already installed."
        return 1
    fi
    sudo mkdir -p "$(dirname -- "$1")"
    printf '%s\n' "$2" | sudo tee "$1" >/dev/null
    echo "Installed $1"
}

# Docker is installed by hand; use sudo when the user is not in the docker group.
docker_cmd() {
    if docker info >/dev/null 2>&1; then
        docker "$@"
    else
        sudo docker "$@"
    fi
}

