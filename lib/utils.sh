#!/usr/bin/env bash
# Shared paths and helpers. Source it, don't run it.
# The variables here are used by the scripts that source this file.
# shellcheck disable=SC2034

REPO_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
BACKUP_DIR="$REPO_DIR/backup"

LLM_HOME="$HOME/LocalLLM"
SEARXNG_DIR="$LLM_HOME/searxng"
WEBUI_DATA_DIR="$HOME/.open-webui"
WEBUI_PYTHON="$HOME/.local/share/uv/tools/open-webui/bin/python"
# services/open-webui.sh runs Open WebUI in backup/open-webui, where it keeps this key.
WEBUI_KEY_FILE="$BACKUP_DIR/open-webui/.webui_secret_key"

# --- Key declarations / sections / selectors (bodies omitted for v1) ---
# This machine's own settings (config/local.example.env), kept out of the repo: where the backup passphrase, the
# encrypted archives and the upload remote are.
LOCAL_ENV_FILE="$HOME/.config/localllm/local.env"
# shellcheck source=/dev/null
[[ -f "$LOCAL_ENV_FILE" ]] && source "$LOCAL_ENV_FILE"
BACKUP_PASSPHRASE_FILE="${BACKUP_PASSPHRASE_FILE:-}"
BACKUP_ARCHIVE_DIR="${BACKUP_ARCHIVE_DIR:-}"
BACKUP_REMOTE="${BACKUP_REMOTE:-}"
BACKUP_KEEP_COUNT="${BACKUP_KEEP_COUNT:-}"
# The versions running when the last backup was made (written by backup.sh, part of the settings backup). On a fresh
# install the installers use them for anything they install new; --update ignores them and takes the newest.
VERSIONS_FILE="$HOME/.config/localllm/versions.env"
# shellcheck source=/dev/null
[[ -f "$VERSIONS_FILE" ]] && source "$VERSIONS_FILE"
# Your own programs that tests/restorability-check.sh ignores (part of the settings backup).
RESTORABILITY_IGNORE_FILE="$HOME/.config/localllm/restorability-ignore"
CHAT_TYPES_DIR="$HOME/.config/localllm/chat-types"
# Where each service runs and its address (config/services.json, for this machine's LOCALLLM_MODE): generated by
# lib/endpoints.py into endpoints.json (read by Pi's extensions) and endpoints.env (read here), again whenever local.env
# or the service list changed. Single mode (the default): everything on 127.0.0.1. When local.env's settings don't fit
# together, ENDPOINTS_ERROR says why and the single-mode addresses are used (./localllm.sh refuses to run then).
ENDPOINTS_DIR="$HOME/.config/localllm"
ENDPOINTS_FILE="$ENDPOINTS_DIR/endpoints.json"
ENDPOINTS_ENV="$ENDPOINTS_DIR/endpoints.env"
SERVICES_FILE="$REPO_DIR/config/services.json"
LLAMA_URL="http://127.0.0.1:8081"
WEBUI_URL="http://127.0.0.1:3000"
SEARXNG_URL="http://127.0.0.1:8080"
SEARCH_GATEWAY_URL="http://127.0.0.1:8090"
ENDPOINTS_ERROR=""
# refresh_endpoints [force]: regenerates endpoints.json/.env when they are older than their sources (or always with
# "force"). Returns 1 and sets ENDPOINTS_ERROR when the settings don't fit together.
refresh_endpoints() {
    local f stale="${1:-}" args=() v
    for f in "$LOCAL_ENV_FILE" "$SERVICES_FILE" "$REPO_DIR/lib/endpoints.py"; do
        [[ "$ENDPOINTS_ENV" -nt "$f" ]] || stale=1
    done
    [[ -f "$ENDPOINTS_FILE" ]] || stale=1
    [[ -n "$stale" ]] || return 0
    args=(LOCALLLM_MODE="${LOCALLLM_MODE:-}" LOCALLLM_APPS="${LOCALLLM_APPS:-}" HELPER_HOST="${HELPER_HOST:-}" MAIN_HOST="${MAIN_HOST:-}")
    for v in $(compgen -v PLACE_); do args+=("$v=${!v}"); done
    if ! ENDPOINTS_ERROR="$(env "${args[@]}" python3 "$REPO_DIR/lib/endpoints.py" write "$ENDPOINTS_DIR" 2>&1)"; then
        ENDPOINTS_ERROR="${ENDPOINTS_ERROR#ERROR: }"
        return 1
    fi
    ENDPOINTS_ERROR=""
}
if refresh_endpoints; then
    # shellcheck source=/dev/null
    source "$ENDPOINTS_ENV"
else
    printf 'WARNING: %s\nUsing the single-mode addresses (127.0.0.1) for now.\n' "$ENDPOINTS_ERROR" >&2
fi
LOCALLLM_MODE="${LOCALLLM_MODE:-single}"
LOCALLLM_APPS="${LOCALLLM_APPS:-pi,owui}"
# apps_has <app>: true when LOCALLLM_APPS includes <app> (pi or owui).
apps_has() { [[ ",${LOCALLLM_APPS:-pi,owui}," == *",$1,"* ]]; }

# The search gateway's own Python environment (install/search-gateway.sh), its settings and its state database.
SEARCH_GATEWAY_VENV="$HOME/.local/share/localllm/search-gateway-venv"
SEARCH_GATEWAY_PYTHON="$SEARCH_GATEWAY_VENV/bin/python"
SEARCH_GATEWAY_SETTINGS="$HOME/.config/localllm/search-gateway.json"
SEARCH_GATEWAY_DB="$HOME/.local/share/localllm/search-gateway.db"

# Only you may read Open WebUI's signing key, its database (your chats) and the backup folder.
# GitHub token file for search gateway (README, "Library docs in Pi"). Without it GitHub allows
# 10 searches a minute instead of 30.
GITHUB_TOKEN_FILE="$HOME/.config/localllm/github-token"
