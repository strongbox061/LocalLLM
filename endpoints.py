#!/usr/bin/env python3
"""Where each service runs and the address its clients use, for this machine's mode.

    python3 lib/endpoints.py write <dir>   writes <dir>/endpoints.json (Pi's extensions) and <dir>/endpoints.env
                                           (lib/common.sh); prints nothing unless something is wrong
    python3 lib/endpoints.py print         the JSON on stdout

The services and their ports come from config/services.json; the mode from the environment, which lib/common.sh fills
from ~/.config/localllm/local.env:
    LOCALLLM_MODE    single (everything on the main PC, the default) or split (some services on the helper PC)
    LOCALLLM_APPS    pi,owui (default) or pi (which apps run)
    HELPER_HOST      the helper PC's Tailscale name (split mode)
"""

import json
import os
import shlex
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SERVICES_FILE = os.path.join(REPO, "config", "services.json")


class SettingsError(Exception):
    pass


def env_name(name):
    """Return the environment variable name for a service endpoint."""
    return f"ENDPOINT_{name.upper().replace('-', '_')}"


def tailscale_self_name():
    """Get this machine's Tailscale hostname, if available."""
    try:
        result = subprocess.run(
            ["tailscale", "status", "--json"],
            capture_output=True, text=True, timeout=5
        )
        if result.returncode == 0:
            data = json.loads(result.stdout)
            me = data.get("Self", {})
            return me.get("DNSName", "").removesuffix(".tailscale")
    except (FileNotFoundError, subprocess.TimeoutExpired, json.JSONDecodeError):
        pass
    return None


def parse_apps(raw):
    """Parse a comma-separated apps string into a list, defaulting to ['pi', 'owui']."""
    if not raw:
        return ["pi", "owui"]
    return [a.strip() for a in raw.split(",") if a.strip()]


def build(environ, services_file=SERVICES_FILE, self_name=tailscale_self_name):
    """Build the endpoints dict from services.json and the current environment."""
    with open(services_file, "r") as f:
        services = json.load(f)

    mode = environ.get("LOCALLLM_MODE", "single")
    apps_raw = environ.get("LOCALLLM_APPS", "pi,owui")
    apps = parse_apps(apps_raw)
    helper_host = environ.get("HELPER_HOST", "")
    self = self_name()

    endpoints = {}

    for svc_name, svc_conf in services.items():
        port = svc_conf.get("port", 0)
        if not port:
            continue

        # Determine which host to use
        host = "127.0.0.1"
        if mode == "split":
            assigned_host = svc_conf.get("host", "main")
            if assigned_host == "helper" and helper_host:
                host = f"{helper_host}.tailscale"
            elif assigned_host == "main" and self:
                host = f"{self}.tailscale"

        endpoints[svc_name] = {
            "host": host,
            "port": port,
            "url": f"http://{host}:{port}",
        }

    return endpoints


def as_env(data, services_file=SERVICES_FILE):
    """Convert the endpoints dict to a shell-friendly env string."""
    lines = ["# Auto-generated by lib/endpoints.py — do not edit"]
    lines.append(f"# Generated from {services_file}")
    lines.append("")

    for svc_name, svc_info in sorted(data.items()):
        env_var = env_name(svc_name)
        url = svc_info["url"]
        lines.append(f"{env_var}={url}")

    return "\n".join(lines) + "\n"


def write(directory, data):
    """Write endpoints.json and endpoints.env into the given directory."""
    os.makedirs(directory, exist_ok=True)

    json_path = os.path.join(directory, "endpoints.json")
    env_path = os.path.join(directory, "endpoints.env")

    with open(json_path, "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")

    with open(env_path, "w") as f:
        f.write(as_env(data))


def main(argv):
    """CLI entry point: 'write <dir>' or 'print'."""
    if len(argv) < 2:
        print("Usage: endpoints.py write <dir> | print", file=sys.stderr)
        sys.exit(1)

    action = argv[1]
    environ = dict(os.environ)

    data = build(environ)

    if action == "write":
        if len(argv) < 3:
            print("Usage: endpoints.py write <dir>", file=sys.stderr)
            sys.exit(1)
        directory = argv[2]
        write(directory, data)
    elif action == "print":
        print(json.dumps(data, indent=2))
    else:
        print(f"Unknown action: {action}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main(sys.argv)
